// Deterministic seed generator. Writes SQL only; placeholder image bytes go into D1 as blob rows.
// Usage: npx tsx backend/scripts/seed.ts --mode=local|remote [--out=<path>]
// Default output is backend/seed/seed.sql. Remote output contains the admin hash, so write it
// outside the repo (--out=<scratch path>) and apply it with `wrangler d1 execute --file`.
// Requires ADMIN_PASSWORD_HASH (a pbkdf2-sha256$... string from scripts/hash-password.ts).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const backendDir = join(here, '..');
const DEFAULT_SEED_SQL = join(backendDir, 'seed', 'seed.sql');
const SEED = 42;
const PRODUCT_COUNT = 100;

const mode = process.argv.find((a) => a.startsWith('--mode='))?.slice('--mode='.length);
if (mode !== 'local' && mode !== 'remote') {
  console.error('Usage: seed.ts --mode=local|remote [--out=<path>]');
  process.exit(1);
}
const outArg = process.argv.find((a) => a.startsWith('--out='))?.slice('--out='.length);
const SEED_SQL = outArg ? resolve(outArg) : DEFAULT_SEED_SQL;
const adminHash = process.env.ADMIN_PASSWORD_HASH;
if (!adminHash || !adminHash.startsWith('pbkdf2-sha256$')) {
  console.error('ADMIN_PASSWORD_HASH must be set to a pbkdf2-sha256$... value');
  process.exit(1);
}

/** mulberry32 PRNG: same seed, same output on every run. */
function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(SEED);
const pick = <T>(xs: readonly T[]): T => xs[Math.floor(rand() * xs.length)] as T;
const between = (min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const sqlStr = (s: string) => `'${s.replace(/'/g, "''")}'`;
const isoNow = '2026-11-26T00:00:00.000Z';

/** Deterministic UUID-shaped string (lowercase hex, 8-4-4-4-12). */
function uuid(): string {
  const hex = (n: number) =>
    Array.from({ length: n }, () => Math.floor(rand() * 16).toString(16)).join('');
  return `${hex(8)}-${hex(4)}-4${hex(3)}-a${hex(3)}-${hex(12)}`;
}

const PRODUCT_CATEGORIES = [
  { id: 1, name: 'Sarees', slug: 'sarees', sort: 1 },
  { id: 2, name: 'Kurtis', slug: 'kurtis', sort: 2 },
  { id: 3, name: 'Lehengas', slug: 'lehengas', sort: 3 },
  { id: 4, name: 'Tops', slug: 'tops', sort: 4 },
  { id: 5, name: 'Accessories', slug: 'accessories', sort: 5 },
];
const SERVICE_CATEGORIES = [
  { id: 6, name: 'Hair', slug: 'hair', sort: 6 },
  { id: 7, name: 'Skin', slug: 'skin', sort: 7 },
  { id: 8, name: 'Nails', slug: 'nails', sort: 8 },
  { id: 9, name: 'Makeup', slug: 'makeup', sort: 9 },
];
const SETTINGS: [string, string][] = [
  ['business_name', 'Noora'],
  ['whatsapp_number', '919999999999'],
  ['address', 'Sample address, City, State'],
  ['opening_hours', 'Mon-Sat 10:00-20:00'],
  ['banner_text', "Noora — beauty parlour & ladies' fashion"],
];

const ADJECTIVES = [
  'Silk',
  'Cotton',
  'Printed',
  'Embroidered',
  'Georgette',
  'Chiffon',
  'Banarasi',
  'Linen',
];
const NOUNS: Record<string, string[]> = {
  sarees: ['Saree', 'Zari Saree', 'Drape Saree'],
  kurtis: ['Kurti', 'Anarkali Kurti', 'A-line Kurti'],
  lehengas: ['Lehenga', 'Bridal Lehenga', 'Party Lehenga'],
  tops: ['Top', 'Blouse', 'Crop Top'],
  accessories: ['Clutch', 'Dupatta', 'Earrings', 'Stole'],
};
const COLOURS = ['Red', 'Maroon', 'Navy', 'Emerald', 'Ivory', 'Pink', 'Black', 'Mustard'];
const SIZES = ['XS', 'S', 'M', 'L', 'XL'];
const SERVICE_NAMES: Record<string, string[]> = {
  hair: [
    'Haircut',
    'Blow Dry',
    'Hair Spa',
    'Keratin Treatment',
    'Hair Colour',
    'Hair Wash',
    'Hair Straightening',
  ],
  skin: [
    'Classic Facial',
    'Cleanup',
    'Gold Facial',
    'Threading',
    'Waxing',
    'Anti-tan Treatment',
    'Bleach',
  ],
  nails: ['Manicure', 'Pedicure', 'Gel Nails', 'Nail Art', 'Nail Extensions'],
  makeup: ['Party Makeup', 'Bridal Makeup', 'Engagement Makeup', 'Mehendi Design', 'Saree Draping'],
};

// 1x1 WebP, used as placeholder bytes for local image blobs.
const PLACEHOLDER_WEBP_HEX = Buffer.from(
  'UklGRiIAAABXRUJQVlA4TBUAAAAvAAAAAAfQ//73v/+BiOh/AAA=',
  'base64',
).toString('hex');

const sql: string[] = [];
sql.push('-- Generated by backend/scripts/seed.ts. Do not edit by hand.');
sql.push(`-- mode=${mode}`);

if (mode === 'local') {
  sql.push(
    'DELETE FROM product_image_blobs;',
    'DELETE FROM product_images;',
    'DELETE FROM product_variants;',
    'DELETE FROM products;',
  );
  sql.push('DELETE FROM services;');
}

for (const c of [...PRODUCT_CATEGORIES, ...SERVICE_CATEGORIES]) {
  const type = c.id <= 5 ? 'product' : 'service';
  sql.push(
    `INSERT INTO categories (id, name, slug, type, sort_order) VALUES (${c.id}, ${sqlStr(c.name)}, ${sqlStr(c.slug)}, '${type}', ${c.sort}) ` +
      'ON CONFLICT(id) DO UPDATE SET name = excluded.name, slug = excluded.slug, type = excluded.type, sort_order = excluded.sort_order;',
  );
}
for (const [key, value] of SETTINGS) {
  sql.push(
    `INSERT INTO settings (key, value) VALUES (${sqlStr(key)}, ${sqlStr(value)}) ` +
      'ON CONFLICT(key) DO UPDATE SET value = excluded.value;',
  );
}
sql.push(
  `INSERT INTO admin_users (username, password_hash) VALUES ('admin', ${sqlStr(adminHash)}) ` +
    'ON CONFLICT(username) DO UPDATE SET password_hash = excluded.password_hash;',
);

if (mode === 'local') {
  for (let id = 1; id <= PRODUCT_COUNT; id++) {
    const cat = pick(PRODUCT_CATEGORIES);
    const adjective = pick(ADJECTIVES);
    const noun = pick(NOUNS[cat.slug] ?? ['Item']);
    const name = `${adjective} ${noun}`;
    const slug = `${adjective.toLowerCase()}-${noun.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${id}`;
    const mrp = between(5, 150) * 100;
    const pct = between(0, 40);
    // Whole rupees, then paise: price is always a multiple of 100 and never above MRP.
    const price = Math.round(((mrp / 100) * (100 - pct)) / 100) * 100;
    const tags = [cat.slug, adjective.toLowerCase(), noun.toLowerCase()].join(',');
    sql.push(
      `INSERT INTO products (id, category_id, name, slug, description, tags, mrp_paise, price_paise, is_active, created_at, updated_at) VALUES ` +
        `(${id}, ${cat.id}, ${sqlStr(name)}, ${sqlStr(slug)}, ${sqlStr(`Placeholder description for ${name}.`)}, ${sqlStr(tags)}, ${mrp}, ${price}, 1, ${sqlStr(isoNow)}, ${sqlStr(isoNow)});`,
    );
    const colourPool = [...COLOURS];
    const variantCount = between(2, 3);
    const sizeOrder = [...SIZES].sort(() => rand() - 0.5).slice(0, variantCount);
    for (let v = 0; v < variantCount; v++) {
      const colour = colourPool.splice(Math.floor(rand() * colourPool.length), 1)[0] ?? 'Black';
      sql.push(
        `INSERT INTO product_variants (product_id, size, colour, sku, stock) VALUES ` +
          `(${id}, ${sqlStr(sizeOrder[v] ?? 'M')}, ${sqlStr(colour)}, ${sqlStr(`SKU-${id}-${v + 1}`)}, ${between(0, 20)});`,
      );
    }
    const imageId = uuid();
    const fullKey = `products/${id}/${imageId}-full.webp`;
    const thumbKey = `products/${id}/${imageId}-thumb.webp`;
    sql.push(
      `INSERT INTO product_images (product_id, r2_key, thumb_r2_key, alt_text, sort_order) VALUES ` +
        `(${id}, ${sqlStr(fullKey)}, ${sqlStr(thumbKey)}, ${sqlStr(name)}, 0);`,
    );
    for (const key of [fullKey, thumbKey]) {
      sql.push(
        `INSERT INTO product_image_blobs (key, content_type, data) VALUES (${sqlStr(key)}, 'image/webp', X'${PLACEHOLDER_WEBP_HEX}');`,
      );
    }
  }

  let serviceId = 1;
  for (const cat of SERVICE_CATEGORIES) {
    const names = SERVICE_NAMES[cat.slug] ?? [];
    for (const name of names) {
      if (serviceId > 25) break;
      const slug = `${cat.slug}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
      sql.push(
        `INSERT INTO services (id, category_id, name, slug, description, price_paise, duration_minutes, is_active) VALUES ` +
          `(${serviceId}, ${cat.id}, ${sqlStr(name)}, ${sqlStr(slug)}, ${sqlStr(`${name} at the parlour.`)}, ${between(2, 40) * 100}, ${between(3, 12) * 15}, 1);`,
      );
      serviceId++;
    }
  }
}

mkdirSync(dirname(SEED_SQL), { recursive: true });
writeFileSync(SEED_SQL, sql.join('\n') + '\n');
console.log(`wrote ${SEED_SQL} (${sql.length} statements)`);
